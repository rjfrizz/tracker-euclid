#!/usr/bin/env python3
"""Generate the TX81Z synth definition (TX81Z.syn) from Edisyn's 4-op editor.

Edisyn (https://github.com/eclab/edisyn, Apache License 2.0, by Sean Luke)
has a tested TX81Z editor. This reads its Yamaha4Op.java for:
  - the order of the VCED and ACED parameter lists, which gives each
    parameter's number in the TX81Z's parameter change messages;
  - each control's label and range (LabelledDial / CheckBox / Chooser);
  - the named choice lists (waves, LFO waves) and the frequency ratio table.
It keeps the TX81Z's parameters (Edisyn's editor also covers the DX21,
DX11, YS/TQ and V50) and groups them the way the Tracker shows them.

Usage: edisyn_tx81z.py path/to/edisyn/synth/yamaha4op/Yamaha4Op.java > TX81Z.syn
"""

import re
import sys


def string_array(src, name):
    m = re.search(r"static String\[\] " + name + r"\s*=\s*new String\[\]\s*\{(.*?)\};", src, re.S)
    if not m:
        m = re.search(r"String\[\] " + name + r"\s*=\s*(?:new String\[\])?\s*\{(.*?)\};", src, re.S)
    if not m:
        raise SystemExit("can't find " + name)
    body = re.sub(r"//[^\n]*", "", m.group(1))
    return re.findall(r'"([^"]*)"', body)


def double_array(src, name):
    m = re.search(r"double\[\] " + name + r"\s*=\s*\{(.*?)\};", src, re.S)
    return [float(x) for x in m.group(1).split(",")]


def controls(src):
    """key -> (label, min, max, centre, list name) from the editor's controls.
    Keys built from an operator number ("operator" + src + "x") are stored
    with OP in place of the number."""
    out = {}
    lines = src.split("\n")
    last_params = None
    for line in lines:
        pm = re.search(r"params = ([A-Z_]+);", line)
        if pm:
            last_params = pm.group(1)
        # The per-operator form first: "operator" alone would match the other.
        key_expr = r'(?:"operator" \+ \w+ \+ "([a-z0-9]+)"|"([a-z0-9]+)")'
        m = re.search(r'new LabelledDial\("([^"]*)", this, ' + key_expr + r', color, (-?\d+), (-?\d+)(?:, (-?\d+))?', line)
        if m:
            label, op, plain, lo, hi, centre = m.groups()
            key = "operatorOP" + op if op else plain
            out.setdefault(key, (label.strip(), int(lo), int(hi), int(centre) if centre else None, None))
            continue
        m = re.search(r'new CheckBox\("([^"]*)", this, ' + key_expr, line)
        if m:
            label, op, plain = m.groups()
            key = "operatorOP" + op if op else plain
            out.setdefault(key, (label.strip(), 0, 1, None, "OFFON"))
            continue
        m = re.search(r'new Chooser\("([^"]*)", this, ' + key_expr + r', params', line)
        if m:
            label, op, plain = m.groups()
            key = "operatorOP" + op if op else plain
            out.setdefault(key, (label.strip(), 0, None, None, last_params))
    return out


def clean(label):
    # Drop Edisyn's model tags like " [11,TX,>,V]" and make labels short.
    label = re.sub(r"\s*\[[^\]]*\]", "", label).strip()
    return label


def main():
    src = open(sys.argv[1]).read()
    vced = string_array(src, "vcedParameters")
    aced = string_array(src, "acedParameters")
    ctl = controls(src)
    lists = {name: string_array(src, name) for name in ("WAVES", "LFO_WAVES", "SHIFTS")}
    ratios = double_array(src, "FREQUENCY_RATIOS")

    def number(key):
        if key in vced:
            return ("vced", vced.index(key))
        if key in aced:
            return ("aced", aced.index(key))
        raise SystemExit("no number for " + key)

    def control(key):
        generic = re.sub(r"operator\d", "operatorOP", key)
        if generic not in ctl:
            raise SystemExit("no control for " + key)
        return ctl[generic]

    out = []
    w = out.append
    w("# Yamaha TX81Z voice editor for the EUCLID edition of the Polyend Tracker.")
    w("# Generated by euclid-synths/tools/edisyn_tx81z.py from Edisyn's Yamaha4Op.java")
    w("# (https://github.com/eclab/edisyn, Apache License 2.0, Copyright Sean Luke).")
    w("# Edits the TX81Z's voice edit buffer with VCED and ACED parameter changes.")
    w('synth "Yamaha TX81Z"')
    w("pause 30")
    w("device 1")
    w("port din")
    w("template vced F0 43 d+10 12 p v F7")
    w("template aced F0 43 d+10 13 p v F7")
    # One request gets the edit buffer as two replies, ACED then VCED (the
    # TX81Z's "LM  8976AE" request, as in Edisyn's requestCurrentDump).
    w("request F0 43 d+20 7E 4C 4D 20 20 38 39 37 36 41 45 F7")
    w("dump vced F0 43 d+00 03 00 5D [ data ] F7")
    w("dump aced F0 43 d+00 7E 00 21 [ 4C 4D 20 20 38 39 37 36 41 45 data ] F7")
    w("name vced 77 10")
    w('list offon "Off" "On"')
    w("list waves " + " ".join('"%s"' % s for s in lists["WAVES"]))
    w("list lfowaves " + " ".join('"%s"' % s for s in lists["LFO_WAVES"]))
    w("list ratios " + " ".join('"%.2f"' % r for r in ratios))
    w('list fixrange "255Hz" "510Hz" "1kHz" "2kHz" "4kHz" "8kHz" "16kHz" "32kHz"')
    w("list shifts " + " ".join('"%s"' % s for s in lists["SHIFTS"]))

    def param(key, name=None, extra="", hi_override=None):
        t, n = number(key)
        label, lo, hi, centre, lst = control(key)
        if hi_override is not None:
            hi = hi_override
        opts = []
        if lst == "OFFON":
            opts.append("list=offon")
        elif lst == "WAVES":
            hi = len(lists["WAVES"]) - 1
            opts.append("list=waves")
        elif lst == "LFO_WAVES":
            hi = len(lists["LFO_WAVES"]) - 1
            opts.append("list=lfowaves")
        if centre is not None:
            opts.append("show=%d" % -centre)
        if extra:
            opts.append(extra)
        w('param %s %d "%s" %d %d%s' % (t, n, name or clean(label), lo, hi, (" " + " ".join(opts)) if opts else ""))

    w('group "Voice"')
    param("algorithm", extra="init=0")
    param("feedback")
    param("transpose", extra="init=24")
    param("pitchbendrange", "Bend range", "init=2")
    param("mono")
    param("fulltimeportamentomode", "Porta full time")
    param("portamentotime", "Porta time")
    param("reverbrate", "Reverb rate")

    w('group "LFO"')
    param("lfowave", "Wave")
    param("lfospeed", "Speed")
    param("lfodelay", "Delay")
    param("lfopitchmodulationdepth", "Pitch depth")
    param("lfoamplitudemodulationdepth", "Amp depth")
    param("lfopitchmodulationsensitivity", "Pitch sens")
    param("lfoamplitudemodulationsensitivity", "Amp sens")
    param("lfosync", "Sync")

    # Operators, numbered as on the TX81Z (the parameter lists run 4, 2, 3, 1).
    for op in (1, 2, 3, 4):
        k = "operator%d" % op
        w('group "Op %d"' % op)
        param(k + "outputlevel", "Level", "init=%d" % (99 if op == 1 else 0))
        param(k + "frequencycoarse", "Ratio", "list=ratios init=4")
        param(k + "frequencyfine", "Fine")
        param(k + "detune", "Detune", "init=3")
        param(k + "operatorwaveform", "Wave")
        param(k + "fix", "Fixed freq")
        param(k + "fixedfrequencyrange", "Fixed range", "list=fixrange")
        param(k + "attackrate", "Attack", "init=31")
        param(k + "decay1rate", "Decay 1")
        param(k + "decay1level", "Decay 1 level", "init=15")
        param(k + "decay2rate", "Decay 2")
        param(k + "releaserate", "Release", "init=15")
        # Edisyn declares this 0-0 first (for models without it); the TX81Z
        # has four settings.
        param(k + "shift", "EG shift", "list=shifts", hi_override=len(lists["SHIFTS"]) - 1)
        param(k + "levelscaling", "Level scaling")
        param(k + "ratescaling", "Rate scaling")
        param(k + "egbiassensitivity", "EG bias")
        param(k + "amplitudemodulationenable", "AM")
        param(k + "keyvelocitysensitivity", "Velocity")

    w('group "Controllers"')
    param("modulationwheelpitch", "Wheel pitch")
    param("modulationwheelamplitude", "Wheel amp")
    param("breathcontrolpitch", "Breath pitch")
    param("breathcontrolamplitude", "Breath amp")
    param("breathcontrolpitchbias", "Breath p bias")
    param("breathcontrolenvelopebias", "Breath EG bias")
    param("footcontrolvolume", "Foot volume")
    param("footcontrolpitch", "Foot pitch")
    param("footcontrolamplitude", "Foot amp")
    # The aftertouch settings are the DX11's (ACED2); the TX81Z has none.

    print("\n".join(out))


if __name__ == "__main__":
    main()
