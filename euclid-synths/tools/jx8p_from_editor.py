#!/usr/bin/env python3
"""Generate the Roland JX-8P tone definition (JX8P.syn).

The parameter table comes from Source/Jx8pSysex.cpp in Grapelane Studio's
Jx8pEditor (https://github.com/grapelanestudios/Jx8pEditor, MIT License,
Copyright (c) 2026 Grapelane Studio): the 44 tone parameters (11-58, less the hardware's gaps) with their
APR/IPR numbers, and the messages, checked there against a JX-8P:
  - an edit is an IPR: F0 41 36 0n 21 20 01 pp vv F7;
  - the whole tone is an APR: F0 41 35 0n 21 20 01, the name (params 0-9),
    then params 10-58, F7.
A JX-8P can't be asked for its tone; it sends the APR when a tone is
chosen on it. So the definition listens: choosing a tone on the JX-8P
fills the page and names the channel.

Values are 0-127 as the JX-8P takes them (it divides some, such as the
waveforms, into a few steps).

Usage: jx8p_from_editor.py path/to/Jx8pSysex.cpp > JX8P.syn
"""

import re
import sys


def main():
    src = open(sys.argv[1]).read()
    body = re.search(r"toneParams\(\)\s*\{.*?=\s*\{(.*?)\};", src, re.S).group(1)
    params = [(int(n), name, int(lo), int(hi))
              for n, _pid, name, lo, hi in re.findall(r'\{\s*(\d+),\s*"(\w+)",\s*"([^"]+)",\s*(\d+),\s*(\d+)\s*\}', body)]
    if len(params) != 44:
        raise SystemExit("expected the 44 tone parameters, found %d" % len(params))

    out = []
    w = out.append
    w("# Roland JX-8P tone editor for the EUCLID edition of the Polyend Tracker.")
    w("# Generated by euclid-synths/tools/jx8p_from_editor.py from Jx8pSysex.cpp in")
    w("# grapelanestudios/Jx8pEditor (MIT License, Copyright (c) 2026 Grapelane Studio).")
    w("# Edits the tone with IPR messages. The JX-8P sends a tone (APR) when one is")
    w("# chosen on it, and this listens for that: there's no asking for it.")
    w("# Device is the JX-8P's MIDI channel.")
    w('synth "Roland JX-8P"')
    w('hint "Pick a tone on the JX-8P: it fills this page"')
    w("pause 20")
    w("device 1")
    w("port din")
    w("listen")
    w("template ipr F0 41 36 d+00 21 20 01 p v F7")
    w("dump ipr F0 41 35 d+00 21 20 01 data F7")
    w("name ipr 0 10")

    groups = [("DCO-1", lambda n: 11 <= n <= 15), ("DCO-2", lambda n: 16 <= n <= 22),
              ("DCO/Mixer", lambda n: 26 <= n <= 32), ("Filter", lambda n: 33 <= n <= 40),
              ("VCA/LFO", lambda n: 41 <= n <= 46 or n == 58), ("Envelopes", lambda n: 47 <= n <= 56)]
    inits = {"VCA Level": 100, "VCF Cutoff": 127, "Mixer DCO-1": 100, "ENV-1 Sustain": 100, "ENV-2 Sustain": 100}
    for title, member in groups:
        w('group "%s"' % title)
        for n, name, lo, hi in params:
            if member(n):
                init = " init=%d" % inits[name] if name in inits else ""
                w('param ipr %d "%s" %d %d%s' % (n, name, lo, hi, init))
    print("\n".join(out))


if __name__ == "__main__":
    main()
