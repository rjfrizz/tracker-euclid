#!/usr/bin/env python3
"""Generate the Roland JV-1080 patch definition (JV1080.syn).

The parameter tables come from RolandJV1080.ini in sonic-codex's
jv1080-sysex-manager (https://github.com/sonic-codex/jv1080-sysex-manager,
MIT License, Copyright (c) 2025 Lt-Blmr), a transcription of the tables in
Roland's JV-1080 MIDI implementation (1-3-1 Patch common, 1-3-2 Patch tone).

A Part group sets the temporary performance's parts (01 00 1p 00): which
patch each plays, its MIDI channel, level, pan and so on; the channel's
Part row picks the part (Auto: the channel's MIDI channel).

The other groups edit the Patch mode temporary patch (03 00 00 00): its common
settings (72 bytes) and tones 1-4 (129 bytes each, from 03 00 10 00, 12 00,
14 00 and 16 00), with DT1 messages; the two-byte settings (tempo, wave
number) go as two 4-bit nibbles. The patch can be got with RQ1 requests.

In the .ini, Patch common offsets are hex; the tone offsets and the
two-byte ("added") settings are decimal, and the tone's last setting
(Reverb send) is at offset 0x80, an address of its own (03 00 11 00).

Usage: jv1080_from_ini.py path/to/RolandJV1080.ini > JV1080.syn
"""

import re
import sys


def sections(text):
    out = {}
    name = None
    for line in text.split("\n"):
        line = line.split(";")[0].strip()
        m = re.match(r"\[(.*)\]", line)
        if m:
            name = m.group(1)
            out[name] = []
            continue
        m = re.match(r"([0-9A-Fa-f]+)\s*=\s*(.+)", line)
        if name and m and "MessageFormat" not in line:
            parts = [p.strip() for p in m.group(2).split(",")]
            out[name].append((m.group(1), parts))
    return out


def shorten(name):
    reps = [("Controller ", "Ctl "), ("destination", "dest"), ("velocity", "vel"), ("Velocity", "Vel"),
            ("sensitivity", "sens"), ("keyfollow", "keyf"), ("frequency", "freq"), ("control", "ctl"),
            ("Control ", "Ctl "), ("switch", "sw"), ("Portamento", "Porta"), ("Structure type", "Structure"),
            ("Booster level", "Booster"), ("EFX:", "EFX "), ("Chorus:", "Chorus "), ("Reverb:", "Reverb "),
            (" cross fade", " xfade"), ("Alternate", "Alt")]
    for a, b in reps:
        name = name.replace(a, b)
    return name[:20]


def main():
    sec = sections(open(sys.argv[1]).read())
    common = sec["Roland JV1080 Patch Mode Temp Patch Common:Sysex"]
    common2 = sec["Roland JV1080 Patch Mode Temp Patch Common:Sysex added"]
    tone = sec["Roland JV1080 Patch Mode Temp Patch Tone1:Sysex"]
    tone2 = sec["Roland JV1080 Patch Mode Temp Patch Tone1:Sysex added"]
    tone3 = sec["Roland JV1080 Patch Mode Temp Patch Tone1:Sysex added2"]

    out = []
    w = out.append
    w("# Roland JV-1080 patch editor for the EUCLID edition of the Polyend Tracker.")
    w("# Generated by euclid-synths/tools/jv1080_from_ini.py from RolandJV1080.ini in")
    w("# sonic-codex/jv1080-sysex-manager (MIT License, Copyright (c) 2025 Lt-Blmr), a")
    w("# transcription of Roland's JV-1080 MIDI implementation tables.")
    w("# Edits the Patch mode temporary patch (put the JV-1080 in Patch mode).")
    w("# Device 1 is the JV-1080's device ID 17 (the usual), Device 2 is 18...")
    w('synth "Roland JV-1080"')
    w("pause 30")
    w("device 1")
    w("port din")
    w("template dt1 F0 41 d+10 6A 12 [ a3 a2 a1 a0 v ] F7")
    w("template dt1n F0 41 d+10 6A 12 [ a3 a2 a1 a0 n1 n0 ] F7")
    w("request F0 41 d+10 6A 11 [ 03 00 00 00 00 00 00 48 ] F7")
    for t in range(4):
        w("request F0 41 d+10 6A 11 [ 03 00 %02X 00 00 00 01 01 ] F7" % (0x10 + 2 * t))
    # The temporary performance's 16 parts (01 00 1p 00, 128 apart): only
    # the Part group's params move with the part; part n listens on MIDI
    # channel n by default.
    w("parts 16 0 channel=1")
    w("request addr=0x01001000 stride=128 F0 41 d+10 6A 11 [ a3 a2 a1 a0 00 00 00 13 ] F7")
    w("dump dt1+dt1n F0 41 d+10 6A 12 [ a3 a2 a1 a0 data ] F7")
    w("name dt1 0x03000000 12")

    inits = {"Patch level": 127, "Patch pan": 64, "Bender range up": 2, "Bender range down": 2,
             "Tone level": 127, "Velocity range upper": 127, "Key range upper": 127, "Output level": 127,
             "Tone pan": 64, "Cutoff frequency": 127, "Fine tune": 50, "Coarse tune": 48,
             "A-ENV level 1": 127, "A-ENV level 2": 127, "A-ENV level 3": 127, "Velocity range lower": 1}

    def param(templ, address, name, lo, hi, extra=""):
        opts = []
        base = name.split(" (")[0]
        if base in inits and lo <= inits[base] <= hi:
            opts.append("init=%d" % inits[base])
        if extra:
            opts.append(extra)
        w('param %s 0x%08X "%s" %d %d%s' % (templ, address, shorten(name), lo, hi, (" " + " ".join(opts)) if opts else ""))

    def rng(parts):
        nums = [int(p) for p in parts[1:] if re.match(r"-?\d+$", p)]
        lo, hi = (nums[0], nums[1]) if len(nums) >= 2 else (1, nums[0]) if nums else (0, 127)
        return parts[0], lo, hi

    # The performance part: which patch it plays, on which channel, how.
    # Offsets 04-05 aren't in the .ini: they're the patch number, two
    # nibbles 0-254 (as the JV-2080's performance part tables have it).
    part = sec["Roland JV1080 Temp Perf. Part1:Sysex"]
    # Where a part's patch comes from: the group type (as the JV-2080's
    # tables name it: user and presets, PCM card, expansion board), then
    # within type 0 the group ID picks the bank (1 user, 2 card, 3-6 presets
    # A-D, from Roland's docs; boards use their own IDs). The JV takes them
    # with the patch number, so changing either sends that again (then=).
    w('list jvgrouptype "User/Preset" "PCM card" "Expansion"')
    ids = ["-", "User", "PCM card", "Preset A", "Preset B", "Preset C", "Preset D"]
    ids += [str(i) for i in range(len(ids), 128)]
    w("list jvgroupid " + " ".join('"%s"' % i for i in ids))
    w('group "Part"')
    for o, p in part:
        name, lo, hi = rng(p)
        off = int(o)
        extra = "stride=128"
        if name == "MIDI channel":
            extra += " show=1"
        if name == "Patch group":
            extra += " list=jvgrouptype then=2"
        if name == "Patch group ID":
            extra += " list=jvgroupid init=1 then=1"
        param("dt1", 0x01001000 + off, name, lo, hi, extra)
        if off == 3:
            param("dt1n", 0x01001004, "Patch number", 0, 254, "stride=128 nibbles=2 show=1")

    # Patch common: offsets in hex; groups of at most 24 rows.
    def common_param(off, parts, nibbles=False):
        name, lo, hi = rng(parts)
        param("dt1n" if nibbles else "dt1", 0x03000000 + off, name, lo, hi, "nibbles=2" if nibbles else "")

    effects = [(int(o, 16), p) for o, p in common if 0x0C <= int(o, 16) <= 0x20]
    fx2 = [(int(o, 16), p) for o, p in common if 0x21 <= int(o, 16) <= 0x2B]
    rest = [(int(o, 16), p) for o, p in common if int(o, 16) >= 0x2E]
    w('group "Common"')
    for o, p in rest[:23]:
        common_param(o, p)
    for o, p in common2:  # Default tempo, two nibbles at (decimal) 44 = 0x2C
        common_param(int(o), p, True)
    w('group "Common 2"')
    for o, p in rest[23:]:
        common_param(o, p)
    w('group "Effects"')
    for o, p in effects:
        common_param(o, p)
    w('group "Chorus/reverb"')
    for o, p in fx2:
        common_param(o, p)

    # Tones 1-4: decimal offsets; the reverb send is at 0x80 (03 00 11 00).
    groups = [("Wave", 0, 20), ("Ctl", 21, 44), ("LFO", 45, 60), ("Pitch", 61, 79), ("Filter", 80, 100),
              ("Amp", 101, 118), ("Pan", 119, 127)]
    for t in range(4):
        base = 0x03001000 + t * 0x200  # 10 00, 12 00, 14 00, 16 00 in 7-bit steps
        for title, a, b in groups:
            w('group "T%d %s"' % (t + 1, title))
            for o, p in tone:
                off = int(o)
                if a <= off <= b:
                    name, lo, hi = rng(p)
                    extra = "init=1" if name == "Tone switch" and t == 0 else ""
                    param("dt1", base + off, name, lo, hi, extra)
            if title == "Wave":
                for o, p in tone2:  # wave number: two nibbles at 3-4
                    name, lo, hi = rng(p)
                    param("dt1n", base + int(o), name, lo, hi, "nibbles=2 show=1")
            if title == "Pan":
                for o, p in tone3:
                    name, lo, hi = rng(p)
                    param("dt1", base + 0x100 + int(o), name, lo, hi)
    print("\n".join(out))


if __name__ == "__main__":
    main()
