#!/usr/bin/env python3
"""Generate the Roland D-110 tone definition (D110.syn) from Edisyn's editor.

Edisyn (https://github.com/eclab/edisyn, Apache License 2.0, by Sean Luke)
has a tested D-110 Tone editor. This reads its RolandD110Tone.java for:
  - the order of the partial parameters (allPartialParameters), which gives
    each one's offset in a partial's 58 bytes;
  - each control's label and range (LabelledDial / CheckBox / Chooser);
  - the keyfollow choice lists.
The addresses follow Edisyn's emit() and requestCurrentDump(): a part's
temporary tone is 246 bytes at 04 00 00 + (part - 1) * 246, with the common
settings first (name at 00, structures at 0A and 0B, partial on/off bits at
0C, envelope mode at 0D) and the four partials of 58 bytes from 0E.

Two of Edisyn's controls are split back into the bytes the D-110 stores:
the partial switches (one byte, a bit each) and the waveform with its PCM
bank (one byte) next to the PCM wave number (the next byte).

Usage: edisyn_d110.py path/to/edisyn/synth/rolandd110/RolandD110Tone.java > D110.syn
"""

import re
import sys

TONE_BASE = 4 * 16384  # 04 00 00, as a plain number
TONE_LENGTH = 246
PARTIAL_START = 0x0E
PARTIAL_LENGTH = 58


def string_array(src, name):
    m = re.search(r"String\[\] " + name + r"\s*=\s*new String\[\]\s*\{(.*?)\};", src, re.S)
    if not m:
        raise SystemExit("can't find " + name)
    body = re.sub(r"//[^\n]*", "", m.group(1))
    return re.findall(r'"([^"]*)"', body)


def controls(src):
    """key -> (label, min, max, subtract) for the partial controls ("p" +
    partial + key) and the common ones."""
    out = {}
    key_expr = r'(?:"p" \+ partial \+ "([a-z0-9]+)"|"([a-z0-9]+)")'
    for m in re.finditer(r'new LabelledDial\("([^"]*)", this, ' + key_expr + r', color, (-?\d+), (-?\d+)(?:, (-?\d+))?', src):
        label, pkey, ckey, lo, hi, sub = m.groups()
        out.setdefault(pkey or ckey, (label, int(lo), int(hi), int(sub) if sub else 0))
    for m in re.finditer(r'new CheckBox\("([^"]*)", this, ' + key_expr, src):
        label, pkey, ckey = m.groups()
        out.setdefault(pkey or ckey, (label, 0, 1, 0))
    return out


def printed(linear):
    """A plain address as the manual prints it: 7 bits a byte."""
    return (linear // 16384) << 16 | ((linear // 128) % 128) << 8 | linear % 128


def main():
    src = open(sys.argv[1]).read()
    partial_params = [p for p in string_array(src, "allPartialParameters")]
    if len(partial_params) != PARTIAL_LENGTH:
        raise SystemExit("expected %d partial parameters, found %d" % (PARTIAL_LENGTH, len(partial_params)))
    ctl = controls(src)
    wg_keyfollow = string_array(src, "WG_KEYFOLLOW")
    tvf_keyfollow = string_array(src, "TVF_KEYFOLLOW")
    notes = string_array(src, "NOTES")

    out = []
    w = out.append
    w("# Roland D-110 tone editor for the EUCLID edition of the Polyend Tracker.")
    w("# Generated by euclid-synths/tools/edisyn_d110.py from Edisyn's RolandD110Tone.java")
    w("# (https://github.com/eclab/edisyn, Apache License 2.0, Copyright Sean Luke).")
    w("# Edits the temporary tone of the channel's Part (1-8) with DT1 messages.")
    w("# Device 1 is the D-110's unit number 17 (the usual one), Device 2 is 18...")
    w('synth "Roland D-110"')
    w("pause 30")
    w("device 1")
    w("port din")
    w("parts 8 %d" % TONE_LENGTH)
    w("template dt1 F0 41 d+10 16 12 [ a2 a1 a0 v ] F7")
    # The whole temporary tone (246 bytes, 01 76 in 7-bit steps), as Edisyn asks.
    w("request addr=0x%06X F0 41 d+10 16 11 [ a2 a1 a0 00 01 76 ] F7" % printed(TONE_BASE))
    w("dump dt1 F0 41 d+10 16 12 [ a2 a1 a0 data ] F7")
    w("name dt1 0x%06X 10" % printed(TONE_BASE))
    w('list onoff "Off" "On"')
    w('list wave "Square b1" "Saw b1" "Square b2" "Saw b2"')
    w("list partials " + " ".join('"%s"' % "".join(str(p + 1) if v & (1 << p) else "-" for p in range(4)) for v in range(16)))
    w("list coarse " + " ".join('"%s%d"' % (notes[v % 12], v // 12 + 1) for v in range(97)))
    w("list wgkf " + " ".join('"%s"' % s for s in wg_keyfollow))
    w("list tvfkf " + " ".join('"%s"' % s for s in tvf_keyfollow))

    def param(offset, name, lo, hi, opts=""):
        w('param dt1 0x%06X "%s" %d %d%s' % (printed(TONE_BASE + offset), name, lo, hi, (" " + opts) if opts else ""))

    def edisyn(key, offset, name, extra=""):
        label, lo, hi, sub = ctl[key]
        opts = []
        if sub:
            opts.append("show=%d" % -sub)
        if extra:
            opts.append(extra)
        param(offset, name or label, lo, hi, " ".join(opts))

    w('group "Common"')
    edisyn("structure1and2", 0x0A, "Structure 1-2")
    edisyn("structure3and4", 0x0B, "Structure 3-4")
    param(0x0C, "Partials", 0, 15, "list=partials init=1")
    edisyn("envmode", 0x0D, "Env no sustain", "list=onoff")

    # Names on the Tracker (Edisyn's labels lean on its layout), and starting
    # values for a plain tone.
    names = {
        "wgpitchcoarse": ("Coarse", "list=coarse init=36"),
        "wgpitchfine": ("Fine", "init=50"),
        "wgpitchkeyfollow": ("Keyfollow", "list=wgkf init=11"),
        "wgpitchbendersw": ("Bend", "list=onoff init=1"),
        "wgpulsewidth": ("Pulse width", ""),
        "wgpwvelosens": ("PW velocity", "init=7"),
        "penvdepth": ("Depth", ""),
        "penvvelosens": ("Velocity", ""),
        "penvtimekeyf": ("Time keyf", ""),
        "penvlevel0": ("Level 0", "init=50"),
        "penvlevel1": ("Level 1", "init=50"),
        "penvlevel2": ("Level 2", "init=50"),
        "penvsustainlevel": ("Sustain", "init=50"),
        "endlevel": ("End level", "init=50"),
        "plforate": ("LFO rate", ""),
        "plfodepth": ("LFO depth", ""),
        "plfomodsens": ("LFO mod", ""),
        "tvfcutofffreq": ("Cutoff", "init=100"),
        "tvfresonance": ("Resonance", ""),
        "tvfkeyfollow": ("Keyfollow", "list=tvfkf init=3"),
        "tvfbiaspoint": ("Bias point", ""),
        "tvfbiaslevel": ("Bias level", "init=7"),
        "tvfenvdepth": ("Env depth", ""),
        "tvfenvvelosens": ("Env velocity", ""),
        "tvfenvdepthkeyfollow": ("Depth keyf", ""),
        "tvfenvtimekeyfollow": ("Time keyf", ""),
        "tvfenvsustainlevel": ("Sustain", ""),
        "tvalevel": ("Level", "init=100"),
        "tvavelosens": ("Velocity", "init=50"),
        "tvabiaspoint1": ("Bias point 1", ""),
        "tvabiaslevel1": ("Bias level 1", "init=12"),
        "tvabiaspoint2": ("Bias point 2", ""),
        "tvabiaslevel2": ("Bias level 2", "init=12"),
        "tvaenvtimekeyfollow": ("Time keyf", ""),
        "tvaenvtime1velfollow": ("T1 velocity", ""),
        "tvaenvlevel1": ("Level 1", "init=100"),
        "tvaenvlevel2": ("Level 2", "init=100"),
        "tvaenvlevel3": ("Level 3", "init=100"),
        "tvaenvsustainlevel": ("Sustain", "init=100"),
    }
    for i in range(1, 6):
        names.setdefault("tvfenvtime%d" % i, ("Time %d" % i, ""))
        names.setdefault("tvaenvtime%d" % i, ("Time %d" % i, ""))
    for i in range(1, 5):
        names.setdefault("penvtime%d" % i, ("Time %d" % i, ""))
    for i in range(1, 4):
        names.setdefault("tvfenvlevel%d" % i, ("Level %d" % i, ""))

    # Groups of at most 23 rows, so each fits under the Synth page's header.
    sections = [
        ("Wave", lambda k: k.startswith("wg")),
        ("Pitch env", lambda k: k.startswith("penv") or k == "endlevel" or k.startswith("plfo")),
        ("Filter", lambda k: k.startswith("tvf")),
        ("Amp", lambda k: k.startswith("tva")),
    ]
    for partial in range(1, 5):
        base = PARTIAL_START + (partial - 1) * PARTIAL_LENGTH
        for title, member in sections:
            w('group "P%d %s"' % (partial, title))
            for i, key in enumerate(partial_params):
                if not member(key):
                    continue
                if key == "wgwaveform":
                    param(base + i, "Wave, bank", 0, 3, "list=wave")
                    continue
                if key == "wgpcmwavenumber":
                    param(base + i, "PCM wave", 0, 127, "show=1")
                    continue
                name, extra = names.get(key, (None, ""))
                edisyn(key, base + i, name, extra)

    print("\n".join(out))


if __name__ == "__main__":
    main()
