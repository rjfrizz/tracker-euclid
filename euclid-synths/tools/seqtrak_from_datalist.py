#!/usr/bin/env python3
"""Generate the Yamaha SEQTRAK definitions (SEQTRAK Drum/Synth/DX.syn) from
Yamaha's SEQTRAK Data List (the PDF, as text: pdftotext -layout).

From the Data List:
  - the Sound List: each sound's number, name and category. Drum sounds are
    1-855, Synth 856-1932, DX 1933-2032 (the Sampler's elements are chosen
    another way, and aren't here);
  - Bank Select / Program Change (MIDI Data Table): Drum, Synth and DX
    sounds are bank MSB 63, LSB 0-31 (Presets 1-32), programs 0-127, so
    sound n is LSB (n - 1) / 128, program (n - 1) % 128;
  - Control Change (MIDI Data Format): the track settings and effect
    controls a track takes as CCs on its MIDI channel;
  - the Arpeggio Preset List: the ARP TEMPLATE names (0 off, 1-15).

Each SEQTRAK track has its own MIDI channel (Kick 1 ... Perc 2 7, Synth 1
8, Synth 2 9, DX 10, Sampler 11): Device follows the channel's MIDI
channel, so that's set to the track's.

Usage: seqtrak_from_datalist.py seqtrak.txt outdir
"""

import os
import re
import sys

RANGES = {"Drum": (1, 855), "Synth": (856, 1932), "DX": (1933, 2032)}
SECTIONS = [("Drum", "Drum Sound"), ("Synth", "Synth Sound"), ("DX", "DX Sound"), ("Sampler", "SAMPLER Sound")]


def sounds(lines):
    """{type: {number: name}} from the Sound List's two-column pages."""
    starts = {}
    for i, l in enumerate(lines):
        for t, head in SECTIONS:
            if l.strip() == head and t not in starts:
                starts[t] = i
    order = [t for t, _ in SECTIONS]
    out = {}
    for k, t in enumerate(order[:-1]):
        a, b = starts[t], starts[order[k + 1]]
        d = {}
        for l in lines[a:b]:
            parts = re.split(r"\s{2,}", l.strip())
            i = 0
            while i < len(parts):
                # "12   Name   Category", or "1933 Name   Category" (4 digits)
                m = re.fullmatch(r"(\d{1,4})(?: (.+))?", parts[i])
                # A page's footer ("4   SEQTRAK Data List") isn't a sound.
                if m and "SEQTRAK Data List" in (m.group(2) or (parts[i + 1] if i + 1 < len(parts) else "")):
                    i += 2
                    continue
                if m and m.group(2):
                    d[int(m.group(1))] = m.group(2)
                    i += 2
                elif m and i + 1 < len(parts):
                    d[int(m.group(1))] = parts[i + 1]
                    i += 3
                else:
                    i += 1
        lo, hi = RANGES[t]
        names = {n: v for n, v in d.items() if lo <= n <= hi}
        missing = [n for n in range(lo, hi + 1) if n not in names]
        if missing:
            raise SystemExit("%s sounds missing: %s" % (t, missing[:10]))
        out[t] = names
    return out


def arp_names(lines):
    i = next(i for i, l in enumerate(lines) if l.strip() == "Arpeggio Preset List")
    names = []
    for l in lines[i + 1:i + 60]:
        m = re.match(r"\s*(\d+)\s{2,}(\S.*?)\s{2,}", l)
        if m and int(m.group(1)) == len(names) + 1:
            names.append(m.group(2))
        if len(names) == 16:
            break
    if len(names) != 16:
        raise SystemExit("can't read the arpeggio presets")
    return names


def q(s):
    return '"%s"' % s.replace('"', "'")


def main():
    lines = open(sys.argv[1]).read().split("\n")
    outdir = sys.argv[2]
    snd = sounds(lines)
    arps = arp_names(lines)
    # EQ: 40 = -12 dB, 64 = 0, 88 = +12 dB, half a dB a step.
    eq = ['"%+.1f dB"' % ((v - 64) / 2.0) for v in range(40, 89)]

    hints = {
        "Drum": "MIDI channel = the track: Kick 1 .. Perc 2 7",
        "Synth": "MIDI channel = the track: Synth 1 8, Synth 2 9",
        "DX": "MIDI channel = the track: DX 10",
    }
    files = {"Drum": "SEQTRAK Drum.syn", "Synth": "SEQTRAK Synth.syn", "DX": "SEQTRAK DX.syn"}
    for t, names in snd.items():
        lo, hi = RANGES[t]
        o = []
        w = o.append
        w("# Yamaha SEQTRAK %s tracks for the EUCLID edition of the Polyend Tracker." % t)
        w("# Generated by euclid-synths/tools/seqtrak_from_datalist.py from Yamaha's")
        w("# SEQTRAK Data List (Sound List, MIDI Data Format and MIDI Data Table).")
        w("# A SEQTRAK track listens on its own MIDI channel (Kick 1 ... Perc 2 7,")
        w("# Synth 1 8, Synth 2 9, DX 10): Device follows the channel's MIDI channel,")
        w("# so set that to the track's.")
        w("# Sound sends bank MSB 63, LSB (sound - 1) / 128 and the program; the rest")
        w("# are the track's control changes. Settings aren't read back (the SEQTRAK")
        w("# has no patch dump), so the page shows what was last sent.")
        w('synth "Yamaha SEQTRAK %s"' % t)
        w('hint "%s"' % hints[t])
        w("pause 2")
        # Follow: the track is the channel's MIDI channel, whatever it is.
        w("device follow")
        w("port din")
        w("template cc d+B0 p v")
        # The sound: bank MSB 63, LSB the value's bits 7-13, program its low 7.
        w("template sound d+B0 00 3F | d+B0 20 vh | d+C0 vl")
        w("list sounds " + " ".join(q(names[n]) for n in range(lo, hi + 1)))
        w("list onoff \"Off\" \"On\"")
        w("list eq " + " ".join(eq))
        if t != "Drum":
            w('list mono "Mono" "Poly" "Chord"')
            w("list arps " + " ".join(q(a) for a in arps))
            w("list arpgate " + " ".join('"%d%%"' % round(v * 200 / 127) for v in range(128)))
            w('list arpspeed "200%" "1" "2" "100%" "4" "5" "6" "7" "8" "25%"')
        w('group "Sound"')
        w('param sound 0 "Sound" %d %d list=sounds init=%d sound=1' % (lo - 1, hi - 1, lo - 1))
        w('group "Track"')
        w('param cc 7 "Volume" 0 127 init=100')
        w('param cc 10 "Pan" 0 127 init=64 show=-64')
        w('param cc 91 "Reverb send" 0 127')
        w('param cc 94 "Delay send" 0 127')
        w('param cc 20 "EQ high" 40 88 init=64 list=eq')
        w('param cc 21 "EQ low" 40 88 init=64 list=eq')
        if t == "Drum":
            w('param cc 25 "Drum pitch" 40 88 init=64 show=-64')
        w('group "Filter/EG"')
        w('param cc 74 "Cutoff" 0 127 init=64 show=-64')
        w('param cc 71 "Resonance" 0 127 init=64 show=-64')
        w('param cc 73 "Attack" 0 127 init=64 show=-64')
        w('param cc 75 "Decay/release" 0 127 init=64 show=-64')
        if t != "Drum":
            w('group "Play"')
            w('param cc 26 "Mono/Poly/Chord" 0 2 init=1 list=mono')
            w('param cc 65 "Portamento" 0 1 list=onoff')
            w('param cc 5 "Portamento time" 0 127')
            w('param cc 27 "Arp" 0 15 list=arps')
            w('param cc 28 "Arp gate" 0 127 init=64 list=arpgate')
            w('param cc 29 "Arp speed" 0 9 init=3 list=arpspeed')
        if t == "DX":
            w('group "FM"')
            w('param cc 116 "Algorithm" 0 11 show=1')
            w('param cc 117 "Mod amount" 0 127')
            w('param cc 118 "Mod frequency" 0 127')
            w('param cc 119 "Feedback" 0 127')
        w('group "Effects"')
        w('param cc 107 "Single FX 1" 0 127')
        w('param cc 108 "Single FX 2" 0 127')
        w('param cc 109 "Single FX 3" 0 127')
        w('param cc 102 "Master FX1 1" 0 127')
        w('param cc 103 "Master FX1 2" 0 127')
        w('param cc 104 "Master FX1 3" 0 127')
        w('param cc 105 "Master FX2" 0 127')
        w('param cc 106 "Master FX3" 0 127')
        w('param cc 110 "Reverb 1" 0 127')
        w('param cc 111 "Reverb 2" 0 127')
        w('param cc 112 "Reverb 3" 0 127')
        w('param cc 113 "Delay 1" 0 127')
        w('param cc 114 "Delay 2" 0 127')
        w('param cc 115 "Delay 3" 0 127')
        with open(os.path.join(outdir, files[t]), "w") as f:
            f.write("\n".join(o) + "\n")
        print(files[t], len(names), "sounds")


if __name__ == "__main__":
    main()
