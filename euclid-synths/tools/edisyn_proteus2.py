#!/usr/bin/env python3
"""Generate the E-mu Proteus/2 preset definition (Proteus2.syn) from Edisyn.

Edisyn (https://github.com/eclab/edisyn, Apache License 2.0, by Sean Luke)
has a tested Proteus 1/2/3 editor. This reads its EmuProteus.java for:
  - the order of its parameters list, which is each parameter's number in a
    parameter change (F0 18 04 id 03 pl ph vl vh F7: 14-bit, LSB first,
    values in two's complement);
  - the Proteus/2 instrument names and the numbers they're sent as
    (PROTEUS_2_MAPPING: not in order, so the definition maps them);
  - the choice lists (LFO shapes, modulation sources and destinations...).
The ranges are Edisyn's controls', written out below by hand (Edisyn makes
many of them in loops).

As Edisyn's notes say, a Proteus can't send its current preset, so this
edits only: there's no request or dump.

Usage: edisyn_proteus2.py path/to/edisyn/synth/emuproteus/EmuProteus.java > Proteus2.syn
"""

import re
import sys


def string_array(src, name):
    m = re.search(name + r"\s*=\s*(?:new String\[\])?\s*\{(.*?)\};", src, re.S)
    if not m:
        raise SystemExit("can't find " + name)
    return re.findall(r'"([^"]*)"', re.sub(r"//[^\n]*", "", m.group(1)))


def int_array(src, name):
    m = re.search(name + r"\s*=\s*new int\[\]\s*\{(.*?)\};", src, re.S)
    return [int(x, 0) for x in re.findall(r"0x[0-9A-Fa-f]+|\d+", re.sub(r"//[^\n]*", "", m.group(1)))]


def main():
    src = open(sys.argv[1]).read()
    params = string_array(src, r"final static String\[\] parameters")
    instruments = string_array(src, "PROTEUS_2_INSTRUMENTS")
    mapping = int_array(src, "PROTEUS_2_MAPPING")
    if len(instruments) != len(mapping):
        raise SystemExit("instrument names and numbers don't match")
    lists = {n: string_array(src, n) for n in (
        "LFO_SHAPES", "CROSSFADE_MODES", "CROSSFADE_DIRECTIONS", "VELOCITY_CURVES", "KEYBOARD_TUNINGS",
        "OUTPUTS", "FOOTSWITCH_DESTINATIONS", "REALTIME_SOURCES", "REALTIME_DESTINATIONS",
        "KEYVEL_SOURCES", "KEYVEL_DESTINATIONS")}

    out = []
    w = out.append
    w("# E-mu Proteus/2 preset editor for the EUCLID edition of the Polyend Tracker.")
    w("# Generated by euclid-synths/tools/edisyn_proteus2.py from Edisyn's EmuProteus.java")
    w("# (https://github.com/eclab/edisyn, Apache License 2.0, Copyright Sean Luke).")
    w("# Edits the current preset with parameter changes. A Proteus can't send its")
    w("# current preset, so there's no getting it (Shift + Insert).")
    w("# Device 1 is the Proteus's MIDI ID 0 (its usual), Device 2 is ID 1...")
    w('synth "E-mu Proteus/2"')
    w("pause 20")
    w("device 1")
    w("port din")
    w("template p F0 18 04 d+00 03 pl ph vl vh F7")
    w('list offon "Off" "On"')
    w("list inst " + " ".join('"%s"' % s for s in instruments))
    w("map inst " + " ".join("0x%04X" % v for v in mapping))
    short = {"LFO_SHAPES": "lfo", "CROSSFADE_MODES": "xfade", "CROSSFADE_DIRECTIONS": "xdir",
             "VELOCITY_CURVES": "velcurve", "KEYBOARD_TUNINGS": "tuning", "OUTPUTS": "output",
             "FOOTSWITCH_DESTINATIONS": "footsw", "REALTIME_SOURCES": "rtsrc", "REALTIME_DESTINATIONS": "rtdst",
             "KEYVEL_SOURCES": "kvsrc", "KEYVEL_DESTINATIONS": "kvdst"}
    for n, l in lists.items():
        w("list %s " % short[n] + " ".join('"%s"' % s for s in l))

    def param(key, name, lo, hi, opts=""):
        if key not in params:
            raise SystemExit("no parameter " + key)
        w('param p %d "%s" %d %d%s' % (params.index(key), name, lo, hi, (" " + opts) if opts else ""))

    def listed(key, name, lst, opts=""):
        n = len(lists[[k for k, v in short.items() if v == lst][0]])
        param(key, name, 0, n - 1, ("list=%s %s" % (lst, opts)).strip())

    for layer, title in ((1, "Primary"), (2, "Secondary")):
        k = "i%d" % layer
        w('group "%s"' % title)
        param(k + "instrument", "Instrument", 0, len(instruments) - 1, "list=inst map=inst init=%d" % (1 if layer == 1 else 0))
        param(k + "volume", "Volume", 0, 127, "init=127")
        param(k + "pan", "Pan", -7, 7, "init=0")
        param(k + "tuningcoarse", "Tune", -36, 36, "init=0")
        param(k + "tuningfine", "Fine tune", -64, 64, "init=0")
        param(k + "samplestartoffset", "Sound start", 0, 127)
        param(k + "delay", "Delay", 0, 127)
        param(k + "lowkey", "Low key", 0, 127)
        param(k + "highkey", "High key", 0, 127, "init=127")
        param(k + "attack", "Attack", 0, 99)
        param(k + "hold", "Hold", 0, 99)
        param(k + "decay", "Decay", 0, 99)
        param(k + "sustain", "Sustain", 0, 99, "init=99")
        param(k + "release", "Release", 0, 99)
        param(k + "envelopeon", "Own envelope", 0, 1, "list=offon")
        param(k + "solomode", "Solo", 0, 1, "list=offon")
        param(k + "chorus", "Chorus", 0, 15)
        param(k + "reversesound", "Reverse", 0, 1, "list=offon")

    w('group "Crossfade"')
    listed("crossfademode", "Mode", "xfade")
    listed("crossfadedirection", "Direction", "xdir")
    param("crossfadebalance", "Balance", 0, 127)
    param("crossfadeamount", "Amount", 0, 255)
    param("switchpoint", "Switch point", 0, 128, "init=60")

    w('group "LFOs"')
    for lfo in (1, 2):
        listed("lfo%dshape" % lfo, "LFO %d shape" % lfo, "lfo")
        param("lfo%dfrequency" % lfo, "LFO %d rate" % lfo, 0, 127)
        param("lfo%ddelay" % lfo, "LFO %d delay" % lfo, 0, 127)
        param("lfo%dvariation" % lfo, "LFO %d variation" % lfo, 0, 127)
        param("lfo%damount" % lfo, "LFO %d amount" % lfo, -128, 127, "init=0")

    w('group "Aux envelope"')
    param("i3amount", "Amount", -128, 127, "init=0")
    param("i3delay", "Delay", 0, 127)
    param("i3attack", "Attack", 0, 99)
    param("i3hold", "Hold", 0, 99)
    param("i3decay", "Decay", 0, 99)
    param("i3sustain", "Sustain", 0, 99)
    param("i3release", "Release", 0, 99)

    w('group "Key/velocity"')
    for i in range(1, 7):
        listed("keyvelsource%d" % i, "%d source" % i, "kvsrc")
        listed("keyveldest%d" % i, "%d destination" % i, "kvdst")
        param("keyvelamount%d" % i, "%d amount" % i, -128, 127, "init=0")

    w('group "Realtime"')
    for i in range(1, 9):
        listed("realtimesource%d" % i, "%d source" % i, "rtsrc")
        listed("realtimedest%d" % i, "%d destination" % i, "rtdst")

    w('group "Controls"')
    for i in range(1, 4):
        listed("footswitchdest%d" % i, "Footswitch %d" % i, "footsw")
    for i, c in enumerate("ABCD", 1):
        param("controlleramount%d" % i, "Controller %s" % c, -128, 127, "init=0")
    param("pressureamount", "Pressure", -128, 127, "init=0")
    param("pitchbendrange", "Bend range", 0, 13, "init=2")
    listed("velocitycurve", "Velocity curve", "velcurve")
    param("keyboardcenter", "Key centre", 0, 128, "init=60")
    listed("submix", "Output", "output")
    listed("keyboardtuning", "Tuning", "tuning")

    w('group "Links"')
    for i in range(1, 4):
        param("link%d" % i, "Link %d preset" % i, -1, 511, "init=-1")
    for i in range(0, 4):
        param("lowkey%d" % i, "Low key %d" % i, 0, 127)
        param("highkey%d" % i, "High key %d" % i, 0, 127, "init=127")

    print("\n".join(out))


if __name__ == "__main__":
    main()
