#!/usr/bin/env python3
"""Generate the Yamaha TX802 / DX7 voice definition (TX802.syn) from Edisyn.

Edisyn (https://github.com/eclab/edisyn, Apache License 2.0, by Sean Luke)
has a tested DX7 editor. The TX802 plays DX7 voices and takes their
parameter changes, so this edits a TX802 voice (or a DX7's) the DX7 way.
It reads YamahaDX7.java for:
  - the order of allParameters, which is each parameter's number in a
    parameter change (F0 43 1n hh pp vv F7, hh = the number's bit 7) and
    its place in a single-voice dump (F0 43 0n 00 01 1B, 155 bytes);
  - each control's label and range, and the choice lists.
The TX802's own extra voice settings (ACED: mono/poly, pitch bend,
portamento, controllers...) and its performance (PCED: each instrument's
voice, channel, volume...) come from Yamaha's TX802 MIDI System Exclusive
Messages tables (parameter changes F0 43 1n 18 / 1A pp dd, requests F0 43
2n 05 and 2n 7E "LM  8952PE", the performance as ASCII hex), with the
factory voice names from the TX802 owner's manual. The instrument (1-8)
is the channel's Part.

Usage: edisyn_dx7.py path/to/edisyn/synth/yamahadx7/YamahaDX7.java > TX802.syn
"""

import re
import sys


# The TX802's factory voices, banks A and B (owner's manual, p. 27).
BANK_A = ['MellowHorn', 'SilvaBrass', 'ReverbBras', 'Tuba', 'Trombone', 'HardTrumps', 'Trumpet A', 'SilvaTrmpt', 'Trumpet B', 'FrenchHorn', 'Strings', 'HallOrch', 'NewOrchest', 'Analog-Str', 'LiveStrg', 'BowedBass', 'EleCello A', 'EleCello B', 'Violins', 'Bassoon', 'Clarinet', 'Oboe', 'Flute', 'SongFlute', 'SpitFlute', 'PanFloot', 'Piccolo', 'Sax', 'Harmonica', 'Harp', 'EbonyIvory', 'PianoBrite', 'Piano 1', 'Piano 2', 'KnockRoad', 'RubbaRoad', 'HardRoads', 'FullTines', 'ClaviStuff', 'Clavi', 'Clavecin', 'ClaviPluck', 'NasalClav', 'HarpsiBox', 'HarpsiWire', 'WireStrg A', 'WireStrg B', 'TouchOrgan', 'ShOrgan', 'TapOrgan', 'BriteOrgan', 'MagicOrgan', 'SoftOrgan', 'PipeOrgan', 'PuffOrgan1', 'PuffPipes', 'PuffOrgan2', 'Harmonium1', 'Harmonium2', 'Whisper A', 'Choir', 'LadyVox', 'MaleChoir', 'Whisper B']
BANK_B = ['SuperBass', 'StringBass', 'SkweekBass', 'SmoohBass', 'BopBass', 'OwlBass', 'JazzBass', 'HardBass', 'GuitarBox', 'PickGuitar', 'FingaPicka', 'LeadaPicka', 'YesBunk', '12 Strings', 'Classipika', 'Shami', 'Maribunba', 'DX Marimba', 'Nu Marimba', 'StonePhone', 'VibraPhone', 'Celeste', 'Swissnare', 'Tom C4', 'CongaDrum', 'Tub Bells', 'Gong', 'Timpani', 'Claves', 'Bells', 'SteelCans', 'Handrum', 'Analog-X', 'FMilters', 'Phasers', 'Ensemble', 'MalletHorn', 'FM-Growth', 'ElectoComb', 'ClariSolo', 'PitchaPad', 'ClaviBrass', 'WhapSynth', 'Whasers', 'Fifths', 'ElecBrass', 'ElectroBak', 'HarmoSynth', 'PianoBells', "St. Elmo's", 'MilkyWays', 'Pluk', 'TingVoice', 'Plukatan', 'OctiLate', 'LateDown', 'Glastine', 'BellWahh', 'RubberGong', 'Wallop', 'Explosion', 'KoikeCycle', 'Thunderon', 'Science']


def string_array(src, name):
    m = re.search(r"String\[\] " + name + r"\s*=\s*(?:new String\[\])?\s*\{(.*?)\};", src, re.S)
    if not m:
        raise SystemExit("can't find " + name)
    body = re.sub(r"//[^\n]*", "", m.group(1))
    return re.findall(r'"([^"]*)"', body)


def controls(src):
    """key -> (label, min, max, subtract) for the controls; per-operator
    keys ("operator" + src/envelope + "x") are stored as operatorOPx."""
    out = {}
    key_expr = r'(?:"operator" \+ \w+ \+ "([a-z0-9]+)"|"([a-z0-9]+)")'
    for m in re.finditer(r'new LabelledDial\("([^"]*)", this, +' + key_expr + r', color, (-?\d+), (-?\d+)(?:, (-?\d+))?', src):
        label, op, plain, lo, hi, sub = m.groups()
        out.setdefault("operatorOP" + op if op else plain, (label, int(lo), int(hi), int(sub) if sub else 0))
    for m in re.finditer(r'new CheckBox\("([^"]*)", this, +' + key_expr, src):
        label, op, plain = m.groups()
        out.setdefault("operatorOP" + op if op else plain, (label, 0, 1, 0))
    return out


def main():
    src = open(sys.argv[1]).read()
    params = string_array(src, "allParameters")
    if len(params) != 155:
        raise SystemExit("expected 155 parameters, found %d" % len(params))
    ctl = controls(src)
    lfo_waves = string_array(src, "LFO_WAVES")
    curves = string_array(src, "KS_CURVES")
    notes = string_array(src, "NOTES")
    coarse = string_array(src, "RATIO_COARSE")
    fine = string_array(src, "RATIO_FINE")

    out = []
    w = out.append
    w("# Yamaha TX802 (and DX7) voice editor for the EUCLID edition of the Polyend Tracker.")
    w("# Generated by euclid-synths/tools/edisyn_dx7.py from Edisyn's YamahaDX7.java")
    w("# (https://github.com/eclab/edisyn, Apache License 2.0, Copyright Sean Luke).")
    w("# Edits the voice edit buffer with DX7 parameter changes, the TX802's extra")
    w("# voice settings (ACED) and the performance's instruments (PCED; the channel's")
    w("# Part is the instrument, 1-8), from Yamaha's TX802 SysEx tables.")
    w('synth "Yamaha TX802"')
    w('hint "Instrument group: pick each instrument\'s voice"')
    w("pause 50")
    w("device 1")
    w("port din")
    w("template vced F0 43 d+10 ph p v F7")
    w("template aced F0 43 d+10 18 p v F7")
    w("template pced F0 43 d+10 1A p v F7")
    # The voice number runs to 255 (presets A and B): two data bytes.
    w("template pcedvoice F0 43 d+10 1A p vh vl F7")
    w("request F0 43 d+20 00 F7")
    w("request F0 43 d+20 05 F7")
    w("request F0 43 d+20 7E 4C 4D 20 20 38 39 35 32 50 45 F7")
    # Instruments 1-8: each performance setting is 8 numbers, one each.
    w("parts 8 0")
    w("dump vced F0 43 d+00 00 01 1B [ data ] F7")
    w("dump aced F0 43 d+00 05 00 31 [ data ] F7")
    w("dump pced+pcedvoice hex F0 43 d+00 7E 01 68 [ 4C 4D 20 20 38 39 35 32 50 45 data ] F7")
    w("name vced 145 10")
    w('list offon "Off" "On"')
    # Voice numbers: internal, cartridge, then the factory banks A and B
    # (names from the TX802 owner's manual's voice list).
    voices = ["I%02d" % i for i in range(1, 65)] + ["C%02d" % i for i in range(1, 65)]
    voices += ["A%02d %s" % (i + 1, n) for i, n in enumerate(BANK_A)]
    voices += ["B%02d %s" % (i + 1, n) for i, n in enumerate(BANK_B)]
    w("list voices " + " ".join('"%s"' % v for v in voices))
    w('list channel ' + " ".join('"%d"' % c for c in range(1, 17)) + ' "Omni"')
    w('list outputs "Off" "I" "II" "I+II"')
    w('list scaling "Normal" "Fractional"')
    w('list lfotrig "Single" "Multi"')
    w('list mode "Ratio" "Fixed"')
    w("list lfowave " + " ".join('"%s"' % s for s in lfo_waves))
    w("list curve " + " ".join('"%s"' % s for s in curves))
    names12 = ["C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"]
    w("list notes " + " ".join('"%s%d"' % (names12[v % 12], v // 12 - 2) for v in range(128)))
    w("list breakpoint " + " ".join('"%s%d"' % (notes[v % 12], (v + 9) // 12 - 1) for v in range(100)))
    w("list coarse " + " ".join('"%s"' % s for s in coarse))
    w("list fine " + " ".join('"%s"' % s for s in fine))

    def number(key):
        return params.index(key)

    def control(key):
        g = re.sub(r"operator\d", "operatorOP", key)
        if g not in ctl:
            raise SystemExit("no control for " + key)
        return ctl[g]

    def param(key, name, extra=""):
        label, lo, hi, sub = control(key)
        opts = []
        if sub:
            opts.append("show=%d" % -sub)
        if extra:
            opts.append(extra)
        w('param vced %d "%s" %d %d%s' % (number(key), name or label, lo, hi, (" " + " ".join(opts)) if opts else ""))

    def listed(key, name, lst, count, extra=""):
        w('param vced %d "%s" 0 %d list=%s%s' % (number(key), name, count - 1, lst, (" " + extra) if extra else ""))

    # The performance's instrument (the Part): its voice and how it plays.
    w('group "Instrument"')
    w('param pcedvoice 16 "Voice" 0 255 list=voices stride=1 reload=1')
    w('param pced 8 "Receive channel" 0 16 list=channel stride=1')
    w('param pced 32 "Volume" 0 99 init=90 stride=1')
    w('param pced 40 "Output" 0 3 list=outputs init=3 stride=1')
    w('param pced 48 "Low limit" 0 127 list=notes stride=1')
    w('param pced 56 "High limit" 0 127 list=notes init=127 stride=1')
    w('param pced 64 "Note shift" 0 48 show=-24 init=24 stride=1')
    w('param pced 24 "Detune" 0 14 show=-7 init=7 stride=1')
    w('param pced 72 "Forced damp" 0 1 list=offon stride=1')
    w('param pced 80 "Alternate assign" 0 1 list=offon stride=1')

    w('group "Voice"')
    param("algorithm", "Algorithm", "init=0")
    param("feedback", "Feedback")
    param("transpose", "Transpose", "init=24")
    listed("oscillatorkeysync", "Osc key sync", "offon", 2, "init=1")

    w('group "LFO"')
    listed("lfowave", "Wave", "lfowave", len(lfo_waves))
    param("lfospeed", "Speed", "init=35")
    param("lfodelay", "Delay")
    param("lfopitchmodulationdepth", "Pitch depth")
    param("lfoamplitudemodulationdepth", "Amp depth")
    param("lfopitchmodulationsensitivity", "Pitch sens", "init=3")
    listed("lfokeysync", "Key sync", "offon", 2, "init=1")

    w('group "Pitch EG"')
    for i in range(1, 5):
        param("pitchegrate%d" % i, "Rate %d" % i, "init=99")
    for i in range(1, 5):
        param("pitcheglevel%d" % i, "Level %d" % i, "init=50")

    # Operators, numbered as on the DX7 (the parameter list runs 6 to 1).
    for op in range(1, 7):
        k = "operator%d" % op
        w('group "Op %d"' % op)
        param(k + "operatoroutputlevel", "Level", "init=%d" % (99 if op == 1 else 0))
        listed(k + "oscillatormode", "Mode", "mode", 2)
        listed(k + "frequencycoarse", "Coarse", "coarse", len(coarse), "init=1")
        listed(k + "frequencyfine", "Fine", "fine", len(fine))
        param(k + "frequencydetune", "Detune", "init=7")
        for i in range(1, 5):
            param(k + "rate%d" % i, "Rate %d" % i, "init=99")
        for i in range(1, 5):
            param(k + "level%d" % i, "Level %d" % i, "init=%d" % (99 if i < 4 else 0))
        listed(k + "keyboardlevelscalingbreakpoint", "Breakpoint", "breakpoint", 100, "init=39")
        param(k + "keyboardlevelscalingleftdepth", "Left depth")
        param(k + "keyboardlevelscalingrightdepth", "Right depth")
        listed(k + "keyboardlevelscalingleftcurve", "Left curve", "curve", len(curves))
        listed(k + "keyboardlevelscalingrightcurve", "Right curve", "curve", len(curves))
        param(k + "keyboardratescaling", "Rate scaling")
        param(k + "amplitudemodulationsensitivity", "Amp mod sens")
        param(k + "keyvelocitysensitivity", "Velocity")

    # The TX802's extra voice settings (ACED), numbered as in its table.
    w('group "Voice 2"')
    w('param aced 15 "Key mode" 0 3')
    w('param aced 16 "Bend range" 0 12 init=2')
    w('param aced 17 "Bend step" 0 12')
    w('param aced 19 "Random pitch" 0 7')
    w('param aced 20 "Porta mode" 0 1')
    w('param aced 21 "Porta step" 0 12')
    w('param aced 22 "Porta time" 0 99')
    w('param aced 12 "Pitch EG range" 0 3')
    w('param aced 14 "Pitch EG velocity" 0 1 list=offon')
    w('param aced 38 "Pitch EG rate scl" 0 7')
    w('param aced 13 "LFO trigger" 0 1 list=lfotrig')
    for op in range(1, 7):
        w('param aced %d "Op %d scaling" 0 1 list=scaling' % (6 - op, op))
    for op in range(1, 7):
        w('param aced %d "Op %d amp mod sens" 0 7' % (12 - op, op))
    w('group "Controllers"')
    for base, title in ((23, "Wheel"), (26, "Foot"), (30, "Breath"), (34, "Aftertouch")):
        w('param aced %d "%s pitch mod" 0 99' % (base, title))
        w('param aced %d "%s amp mod" 0 99' % (base + 1, title))
        w('param aced %d "%s EG bias" 0 99' % (base + 2, title))
        if title == "Foot":
            w('param aced 29 "Foot volume" 0 99')
        if title in ("Breath", "Aftertouch"):
            w('param aced %d "%s pitch bias" 0 100 show=-50 init=50' % (base + 3, title))
    print("\n".join(out))


if __name__ == "__main__":
    main()
